/** 규격이 어긋났을 때 등급이 밀리는 칸. ⚠️ **클레임을 만들지 않는다** — 팝업 업무에는
 *  이미 등록 기간 클레임이 있고, 벌이 둘이면 이 업무만 유독 가혹해진다. 등급 하나로 흐르면
 *  대금·평판·만족도가 이미 그 뒤를 따른다(키워드 보정과 같은 고리). */
